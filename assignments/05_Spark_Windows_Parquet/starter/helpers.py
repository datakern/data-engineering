"""
DataKern | Assignment 5 | GIVEN HELPERS (you do not edit this file)

  get_spark()      one place that builds a local SparkSession
  csv_path(name)   full path of an Olist CSV file (friendly error if it is missing)
  fresh_dir(path)  delete a folder if it exists, so a re-run starts clean
  uri(path)        a path string that Spark understands on Windows, Mac and Linux
  count_files()    how many .parquet (or other) files sit under a folder
  folder_size_mb() size of a folder on disk, in MB
  plan_text(df)    the physical plan of a DataFrame as text (to prove what Spark did)
  timed(fn)        run fn(), return (result, seconds)
"""
import os
import shutil
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Olist CSV files: put them in  data/olist/  next to this file, or set OLIST_DIR.
DATA_DIR = Path(os.environ.get("OLIST_DIR", HERE / "data" / "olist"))
# Everything your code writes goes here. Safe to delete.
OUT_DIR = HERE / "output"

# PySpark must start the SAME Python you are running now (matters on Windows and in a venv).
os.environ.setdefault("PYSPARK_PYTHON", sys.executable)
os.environ.setdefault("PYSPARK_DRIVER_PYTHON", sys.executable)


def get_spark(app="DataKern assignment 5"):
    from pyspark.sql import SparkSession

    spark = (
        SparkSession.builder.master("local[*]")
        .appName(app)
        .config("spark.sql.shuffle.partitions", "8")
        .config("spark.ui.showConsoleProgress", "false")
        .config("spark.driver.memory", os.environ.get("DRIVER_MEM", "2g"))
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("WARN")  # keep WARN: Spark warns about bad window specs
    print(f"Spark {spark.version} | Spark UI: {spark.sparkContext.uiWebUrl}")
    return spark


def csv_path(name):
    p = DATA_DIR / name
    if not p.exists():
        sys.exit(
            f"\nCannot find {p}\n"
            f"Put the Olist CSV files in {DATA_DIR} or set the OLIST_DIR environment variable."
        )
    return p.as_posix()


def fresh_dir(path):
    path = Path(path)
    if path.exists():
        shutil.rmtree(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def uri(path):
    return Path(path).as_posix()


def count_files(path, suffix=".parquet"):
    return sum(1 for _, _, fs in os.walk(path) for f in fs if f.endswith(suffix))


def folder_size_mb(path):
    total = sum(os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(path) for f in fs)
    return total / (1024 * 1024)


def plan_text(df):
    """Physical plan as text. Look for 'PartitionFilters', 'PushedFilters', 'EvalPython'."""
    return df._jdf.queryExecution().executedPlan().toString()


def timed(fn):
    t0 = time.perf_counter()
    result = fn()
    return result, time.perf_counter() - t0
